"""Checks on P2, the SED extrapolation model.

    python tests/test_p2.py

P2's claim is that it *knows about wavelength*. These tests are mostly about
proving that claim is real rather than decorative -- most importantly, that
permuting the input bands breaks it, which is exactly what B1 and B2 would
shrug off.
"""

from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

import numpy as np
import torch
import yaml

from src.config import BANDS, INPUT_BAND_IDX, TARGET_BAND_IDX
from src.models.p2_sed import P2SED, build_p2, projection_to_coefficients
from src.physics import bands as band_mod
from src.physics import sed

PASS, FAIL = 0, 0


def check(label: str, got, want=True, tol: float | None = None) -> None:
    global PASS, FAIL
    if tol is not None:
        ok = bool(np.all(np.abs(np.asarray(got, dtype=float)
                                - np.asarray(want, dtype=float)) <= tol))
    else:
        ok = bool(got == want)
    if ok:
        PASS += 1
        print(f"  PASS  {label}")
    else:
        FAIL += 1
        print(f"  FAIL  {label}: got {got!r}, want {want!r}")


def _cube(rng, h=8, w=8):
    return rng.normal(size=(len(BANDS), h, w))


def _inputs(cube):
    return torch.tensor(cube[list(INPUT_BAND_IDX)],
                        dtype=torch.float32).unsqueeze(0)


# ------------------------------------------------------- the physics itself
def test_matches_the_numpy_reference_at_init() -> None:
    """At init, P2 must BE the zero-parameter least-squares extrapolation."""
    print("\nP2 starts as the pure physics answer")
    rng = np.random.default_rng(0)
    cube = _cube(rng)
    ref = sed.fit_sed_and_predict(cube, degree=2)
    got = P2SED()(_inputs(cube)).detach().numpy()[0, 0]
    check("torch forward equals the numpy reference fit",
          float(np.abs(ref - got).max()) < 1e-5)


def test_recovers_a_known_spectrum_exactly() -> None:
    """Build a pixel that IS a quadratic in log lambda; P2 must nail y."""
    print("\nit recovers a spectrum it can represent")
    A = sed.design_matrix(degree=2)
    coef = np.array([0.7, -1.3, 0.4])
    observed = A @ coef
    truth = float(sed.target_vector(degree=2) @ coef)

    x = torch.tensor(observed, dtype=torch.float32).view(1, 4, 1, 1)
    got = float(P2SED()(x).detach()[0, 0, 0, 0])
    check(f"predicted y matches the true {truth:.4f}", got, truth, tol=1e-4)

    # A straight line is a special case and must also be exact.
    coef_lin = np.array([0.2, 0.9, 0.0])
    x2 = torch.tensor(A @ coef_lin, dtype=torch.float32).view(1, 4, 1, 1)
    want = float(sed.target_vector(degree=2) @ coef_lin)
    check("and a pure straight line too",
          float(P2SED()(x2).detach()[0, 0, 0, 0]), want, tol=1e-4)


def test_it_knows_the_bands_are_ordered_in_wavelength() -> None:
    """The claim that separates P2 from B1 and B2.

    B1 and B2 are invariant to permuting input channels -- shuffle g,r,i,z and
    retrain and they reach the same loss, because neither is told the inputs
    are ordered. P2 must not be invariant.
    """
    print("\nit is NOT permutation invariant")
    rng = np.random.default_rng(3)
    x = _inputs(_cube(rng))
    m = P2SED()
    base = m(x)
    for a, b in ((0, 1), (2, 3), (0, 3)):
        order = list(range(4))
        order[a], order[b] = order[b], order[a]
        swapped = m(x[:, order])
        check(f"swapping {BANDS[a]} and {BANDS[b]} changes the prediction",
              float((base - swapped).abs().max()) > 1e-5)


def test_the_target_is_extrapolation_not_interpolation() -> None:
    """If y ever became an interpolation, P2's hard part would have vanished."""
    print("\nthe target sits beyond the inputs")
    geo = band_mod.extrapolation_baseline()
    check("y is redder than every input", geo["is_extrapolation"])
    v = sed.target_vector(degree=2)
    A = sed.design_matrix(degree=2)
    # The evaluation point must lie outside the convex hull of the input
    # basis rows along the linear term, i.e. past the reddest band.
    check("the evaluation point is past the reddest input row",
          float(v[1]) > float(A[:, 1].max()))


def test_projection_is_a_true_least_squares_solution() -> None:
    print("\nthe projection matrix")
    for degree in (1, 2, 3):
        P = projection_to_coefficients(degree)
        A = sed.design_matrix(degree=degree)
        check(f"degree {degree}: shape is ({degree + 1}, 4)",
              P.shape, (degree + 1, 4))
        # P A must be the identity: fitting data generated BY the basis
        # returns its own coefficients.
        check(f"degree {degree}: P @ A is the identity",
              P @ A, np.eye(degree + 1), tol=1e-6)


def test_target_channel_never_reaches_the_model() -> None:
    print("\nno leakage of y")
    rng = np.random.default_rng(5)
    cube = _cube(rng)
    m = P2SED()
    a = m(_inputs(cube))
    cube[TARGET_BAND_IDX] += 1000.0
    b = m(_inputs(cube))
    check("corrupting the y channel changes nothing",
          float((a - b).abs().max()), 0.0, tol=0.0)
    check("the model only ever takes 4 channels",
          m.sed.projection.shape[1], 4)


# ------------------------------------------------------------ the model API
def test_parameter_counts() -> None:
    print("\nparameter counts")
    m = P2SED()
    b = m.parameter_breakdown()
    check("three gains for a quadratic", b["sed_gains"], 3)
    check("one bias", b["sed_bias"], 1)
    check("four trainable in the pure form", b["trainable"], 4)
    check("no residual by default", b["residual"], 0)

    r = P2SED(residual=True).parameter_breakdown()
    check("the residual head adds 737", r["residual"], 737)
    check("741 in total with it", r["trainable"], 741)

    cfg = yaml.safe_load((Path(__file__).resolve().parents[1] / "config"
                          / "p2_sed.yaml").read_text(encoding="utf-8"))
    check("the config builds the pure form",
          build_p2(cfg["model"]).count_parameters(), 4)
    try:
        build_p2(dict(cfg["model"], expected_parameters=99))
        check("a count mismatch is refused", False)
    except ValueError:
        check("a count mismatch is refused", True)

    try:
        P2SED(in_channels=3)
        check("a wrong channel count is refused", False)
    except ValueError:
        check("a wrong channel count is refused", True)


def test_residual_starts_as_a_no_op() -> None:
    """Any gain from the residual must be attributable to the residual."""
    print("\nthe residual head is zero-initialised")
    rng = np.random.default_rng(7)
    x = _inputs(_cube(rng))
    torch.manual_seed(0)
    pure = P2SED()
    torch.manual_seed(0)
    withres = P2SED(residual=True)
    check("at init, with and without the residual agree exactly",
          float((pure(x) - withres(x)).abs().max()), 0.0, tol=1e-6)

    withres.residual.net[-1].weight.data.normal_(0, 0.1)
    check("once trained it does contribute",
          float((pure(x) - withres(x)).abs().max()) > 1e-6)


def test_gains_are_learnable_and_reportable() -> None:
    print("\nfitted gains")
    m = P2SED()
    rep = m.fitted_gains()
    check("gains start at 1 (pure physics)", rep["gains"], [1.0, 1.0, 1.0],
          tol=1e-9)
    check("nothing departs from pure physics at init",
          any(rep["departs_from_pure_physics"]), False)
    check("terms are named by their power of log lambda",
          rep["terms"], ["log_lambda^0", "log_lambda^1", "log_lambda^2"])

    x = torch.randn(2, 4, 8, 8)
    m(x).pow(2).mean().backward()
    check("the gains receive a gradient",
          bool(m.sed.gains.grad is not None
               and m.sed.gains.grad.abs().sum() > 0))

    with torch.no_grad():
        m.sed.gains[2] = 0.3
    check("a departure is flagged",
          m.fitted_gains()["departs_from_pure_physics"][2], True)

    frozen = P2SED(learn_gains=False)
    check("learn_gains=False freezes them",
          frozen.sed.gains.requires_grad, False)
    check("leaving only the bias trainable", frozen.count_parameters(), 1)


def test_shapes_and_conditioning_signature() -> None:
    print("\nshapes")
    m = P2SED()
    x = torch.randn(3, 4, 16, 16)
    check("output is (N, 1, H, W)", tuple(m(x).shape), (3, 1, 16, 16))
    check("an unused cond argument is accepted",
          tuple(m(x, torch.rand(3)).shape), (3, 1, 16, 16))
    check("odd sizes are fine -- there is no downsampling",
          tuple(m(torch.randn(1, 4, 13, 7)).shape), (1, 1, 13, 7))


def test_it_beats_copy_z_on_a_synthetic_spectrum() -> None:
    """P2 must beat B0 where the physics is real, or it is not doing physics."""
    print("\nit beats copy-z on data with a genuine spectral slope")
    rng = np.random.default_rng(11)
    A = sed.design_matrix(degree=2)
    tv = sed.target_vector(degree=2)
    coef = rng.normal(size=(3, 64))
    observed = (A @ coef).astype(np.float32)          # (4, 64)
    truth = (tv @ coef).astype(np.float32)            # (64,)

    x = torch.tensor(observed, dtype=torch.float32).T.reshape(64, 4, 1, 1)
    pred = P2SED()(x).detach().numpy().reshape(-1)
    copy_z = observed[3]                              # B0 without its scale

    mae_p2 = float(np.abs(pred - truth).mean())
    mae_b0 = float(np.abs(copy_z - truth).mean())
    check(f"P2 MAE {mae_p2:.2e} beats copy-z {mae_b0:.2e}", mae_p2 < mae_b0)
    check("and P2 is essentially exact here", mae_p2 < 1e-4)


def main() -> int:
    print("=" * 70)
    print("P2 -- SED extrapolation model")
    print("=" * 70)
    test_matches_the_numpy_reference_at_init()
    test_recovers_a_known_spectrum_exactly()
    test_it_knows_the_bands_are_ordered_in_wavelength()
    test_the_target_is_extrapolation_not_interpolation()
    test_projection_is_a_true_least_squares_solution()
    test_target_channel_never_reaches_the_model()
    test_parameter_counts()
    test_residual_starts_as_a_no_op()
    test_gains_are_learnable_and_reportable()
    test_shapes_and_conditioning_signature()
    test_it_beats_copy_z_on_a_synthetic_spectrum()
    print("\n" + "=" * 70)
    print(f"{PASS} passed, {FAIL} failed")
    print("=" * 70)
    return 1 if FAIL else 0


if __name__ == "__main__":
    sys.exit(main())
